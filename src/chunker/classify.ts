import { changedSpan, isWhitespaceOnly, parsePatch } from "../diff/parse-patch.js";
import type { ChangedFile, ClassifiedFile, FileRole, NoiseReason } from "../types.js";

const LOCKFILES = new Set([
  "package-lock.json",
  "npm-shrinkwrap.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "bun.lockb",
  "bun.lock",
  "Cargo.lock",
  "poetry.lock",
  "Pipfile.lock",
  "uv.lock",
  "Gemfile.lock",
  "composer.lock",
  "go.sum",
]);

const GENERATED_PATH = [
  /(^|\/)(dist|build|out|coverage|\.next|\.nuxt)\//,
  /\.min\.(js|css)$/,
  /\.map$/,
  /\.generated\.\w+$/,
  /(^|\/)generated\//,
  /\.pb\.(go|ts|js)$/,
  /_pb2(_grpc)?\.py$/,
];
const GENERATED_MARKER = /@generated|DO NOT EDIT|auto-generated|autogenerated/i;
const VENDORED_PATH = /(^|\/)(node_modules|vendor|third_party)\//;
const SNAPSHOT_PATH = /(^|\/)__snapshots__\/|\.snap$/;
const BINARY_PATH =
  /\.(png|jpe?g|gif|webp|avif|bmp|ico|icns|tiff?|psd|pdf|zip|gz|tgz|bz2|xz|7z|rar|jar|war|woff2?|ttf|otf|eot|mp[34]|m4a|wav|ogg|flac|mov|avi|webm|mkv|exe|dll|so|dylib|a|o|class|pyc|wasm|bin|dat|db|sqlite3?|xlsx?|docx?|pptx?)$/i;

const TEST_PATH = [/(^|\/)(__tests__|tests?|spec|e2e)\//, /\.(test|spec)\.[cm]?[jt]sx?$/];
const TYPES_PATH = [
  /\.d\.[cm]?ts$/,
  /\.types?\.[cm]?[jt]s$/,
  /(^|\/)types?\.[cm]?[jt]s$/,
  /(^|\/)(types|interfaces|models|schemas?)\//,
];
const DOCS_PATH = [/\.(md|mdx|rst|txt|adoc)$/i, /(^|\/)docs?\//];
const CONFIG_PATH = [
  /(^|\/)package\.json$/,
  /(^|\/)tsconfig[\w.-]*\.json$/,
  /(^|\/)\.github\//,
  /(^|\/)\.?(eslint|prettier|babel|jest|vitest|vite|webpack|rollup)[\w.-]*\.(c?js|mjs|cts|ts|json|ya?ml)$/,
  /(^|\/)\.[\w.-]*rc(\.\w+)?$/,
  /(^|\/)Dockerfile[\w.-]*$/,
  /\.(ya?ml|toml|ini)$/,
  /(^|\/)\.env[\w.-]*$/,
];

const basename = (path: string) => path.slice(path.lastIndexOf("/") + 1);

export function fileRole(path: string): FileRole {
  if (TEST_PATH.some((re) => re.test(path))) return "test";
  if (DOCS_PATH.some((re) => re.test(path))) return "docs";
  if (CONFIG_PATH.some((re) => re.test(path))) return "config";
  if (TYPES_PATH.some((re) => re.test(path))) return "types";
  return "source";
}

function noiseReason(file: ChangedFile, whitespaceOnly: boolean): NoiseReason | undefined {
  if (LOCKFILES.has(basename(file.path))) return "lockfile";
  if (VENDORED_PATH.test(file.path)) return "vendored";
  if (GENERATED_PATH.some((re) => re.test(file.path))) return "generated";
  if (file.patch && GENERATED_MARKER.test(file.patch.slice(0, 2000))) return "generated";
  if (SNAPSHOT_PATH.test(file.path)) return "snapshot";
  if (file.status === "renamed" && file.additions + file.deletions === 0) return "rename";
  if (!file.patch && file.additions + file.deletions === 0) {
    // GitHub reports binary files and empty files the same way: no patch, no changed lines.
    if (BINARY_PATH.test(file.path)) return "binary";
    if (file.status === "added" || file.status === "removed") return "empty";
    return "no-line-changes"; // e.g. a permission change, or a binary type we don't know
  }
  if (whitespaceOnly) return "whitespace";
  return undefined;
}

export function classifyFile(file: ChangedFile): ClassifiedFile {
  const hunks = file.patch ? parsePatch(file.patch) : [];
  const noise = noiseReason(file, isWhitespaceOnly(hunks));
  return {
    ...file,
    role: fileRole(file.path),
    noise,
    patchMissing: !file.patch && !noise,
    hunks,
    span: changedSpan(hunks),
  };
}
