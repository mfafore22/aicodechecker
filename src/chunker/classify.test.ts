import { describe, expect, it } from "vitest";
import type { ChangedFile } from "../types.js";
import { classifyFile, fileRole } from "./classify.js";

const file = (over: Partial<ChangedFile>): ChangedFile => ({
  path: "src/a.ts",
  status: "modified",
  additions: 1,
  deletions: 0,
  patch: "@@ -1 +1,2 @@\n a\n+b",
  ...over,
});

describe("fileRole", () => {
  it.each([
    ["src/api/users.test.ts", "test"],
    ["tests/helpers.ts", "test"],
    ["src/__tests__/x.js", "test"],
    ["README.md", "docs"],
    ["docs/setup.ts", "docs"],
    ["package.json", "config"],
    ["tsconfig.build.json", "config"],
    [".github/workflows/ci.yml", "config"],
    ["Dockerfile", "config"],
    [".eslintrc.cjs", "config"],
    ["src/types.ts", "types"],
    ["src/global.d.ts", "types"],
    ["src/models/user.ts", "types"],
    ["src/api/users.ts", "source"],
  ])("%s → %s", (path, role) => {
    expect(fileRole(path)).toBe(role);
  });
});

describe("classifyFile noise", () => {
  it.each([
    [file({ path: "package-lock.json" }), "lockfile"],
    [file({ path: "web/yarn.lock" }), "lockfile"],
    [file({ path: "vendor/lib/x.go" }), "vendored"],
    [file({ path: "dist/index.js" }), "generated"],
    [file({ path: "app.min.js" }), "generated"],
    [file({ patch: "@@ -0,0 +1 @@\n+// Code generated by protoc. DO NOT EDIT." }), "generated"],
    [file({ path: "src/__snapshots__/a.test.ts.snap" }), "snapshot"],
    [file({ status: "renamed", previousPath: "src/b.ts", additions: 0, patch: undefined }), "rename"],
    [file({ patch: "@@ -1 +1 @@\n-  a\n+    a" }), "whitespace"],
  ] as const)("%#: %s", (input, reason) => {
    expect(classifyFile(input).noise).toBe(reason);
  });

  it("marks a binary file by its extension", () => {
    expect(classifyFile(file({ path: "logo.png", status: "added", additions: 0, patch: undefined })).noise).toBe(
      "binary",
    );
  });

  it("marks a new empty file as empty, not binary", () => {
    const result = classifyFile(file({ path: "src/__init__.py", status: "added", additions: 0, patch: undefined }));
    expect(result.noise).toBe("empty");
    expect(result.patchMissing).toBe(false);
  });

  it("marks a modified file with no line changes (e.g. chmod)", () => {
    expect(classifyFile(file({ path: "run.sh", additions: 0, patch: undefined })).noise).toBe("no-line-changes");
  });

  it("leaves a normal change alone", () => {
    const result = classifyFile(file({}));
    expect(result.noise).toBeUndefined();
    expect(result.role).toBe("source");
    expect(result.span).toEqual([2, 2]);
  });
});

describe("classifyFile patchMissing", () => {
  it("is set when GitHub left out the diff of a real change", () => {
    const result = classifyFile(file({ additions: 5000, deletions: 10, patch: undefined }));
    expect(result.noise).toBeUndefined();
    expect(result.patchMissing).toBe(true);
  });
});
